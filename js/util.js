/** Экранирование строки для безопасной вставки в HTML. */
function escHtml(s) {
  return String(s).replace(/[&<>"']/g, c =>
    ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

/** Ключ дня вида "ГГГГ-ММ-ДД" (локальное время). */
function dateKey(d) {
  const x = d || new Date();
  const p = n => String(n).padStart(2, '0');
  return `${x.getFullYear()}-${p(x.getMonth() + 1)}-${p(x.getDate())}`;
}

/** Метка времени конца сегодняшнего дня (полночь). */
function endOfTodayTs() {
  const d = new Date();
  d.setHours(24, 0, 0, 0);
  return d.getTime();
}
