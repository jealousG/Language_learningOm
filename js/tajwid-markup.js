/**
 * Слой разметки. Внесено только проверенное вручную.
 * Сура «Ан-Нас» (114): идгам шамси во всех словах النَّاسِ / الْخَنَّاسِ
 * (артикль перед солнечной буквой с шадда — хорошо виден в тексте).
 */
const TAJWID_MARKUP = {
  'q114:1': [ { w: 3, rule: 'idgham_shamsi' } ], // النَّاسِ в قُلْ أَعُوذُ بِرَبِّ النَّاسِ
  'q114:2': [ { w: 1, rule: 'idgham_shamsi' } ], // النَّاسِ в مَلِكِ النَّاسِ
  'q114:3': [ { w: 1, rule: 'idgham_shamsi' } ], // النَّاسِ في إِلَٰهِ النَّاسِ
  'q114:4': [ { w: 1, rule: 'idgham_shamsi' } ]  // الْخَنَّاسِ в الْوَسْوَاسِ الْخَنَّاسِ
};

/** Метки таджвида для предложения. key = "storyId:ayah" (или индекс). */
function getTajwidMarks(story, sentence, sIdx) {
  if (!story || !sentence) return [];
  const key = story.id + ':' + (sentence.ayah != null ? sentence.ayah : sIdx);
  return TAJWID_MARKUP[key] || [];
}

/** Есть ли вообще разметка для текста. */
function storyHasTajwid(story) {
  if (!story) return false;
  return story.sentences.some((s, i) => getTajwidMarks(story, s, i).length > 0);
}
