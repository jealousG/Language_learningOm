// ============================================================
//  Таджвид — фундамент без ложных обещаний.
//
//  Что здесь есть:
//   1) TAJWID_RULES — реестр правил с краткими техническими
//      пояснениями (тексты подсказок);
//   2) TAJWID_MARKUP — ОТДЕЛЬНЫЙ слой разметки, не трогающий
//      данные текстов. Разметка подключается только вручную
//      и только достоверная.
//
//  Чего здесь НЕТ (намеренно):
//   - автоматической оценки таджвида;
//   - автоматической генерации разметки по тексту;
//   - «цветных правил» там, где разметка не добавлена.
//
//  Схема слоя разметки (для будущих добавлений):
//    TAJWID_MARKUP["<storyId>:<аят|индекс предложения>"] = [
//      { w: <индекс слова в предложении, начиная с 0>, rule: "<ключ из TAJWID_RULES>" }
//    ]
//  Разметка применяется только в включаемом режиме «Таджвид»
//  и только к визуальной копии — данные текста не меняются.
// ============================================================

